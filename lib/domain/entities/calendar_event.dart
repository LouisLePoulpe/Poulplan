import 'package:meta/meta.dart';

/// Where a displayed event comes from: only [event] is stored and editable
/// as such; the others are generated for display.
enum EventKind { event, holiday, schoolHoliday, birthday }

/// What a recurring series does with occurrences falling on public holidays.
enum HolidayRule { none, skip, nextWorkingDay, previousWorkingDay }

/// A calendar event as seen by the rest of the app.
///
/// Times are stored in UTC:
/// - timed events: [start]/[end] are real instants and [timeZone] is the IANA
///   zone the event was entered in;
/// - all-day events: [start]/[end] are UTC midnights encoding *floating* dates
///   (the event stays on the same dates whatever the device's zone), with
///   [end] exclusive.
@immutable
class CalendarEvent {
  const CalendarEvent({
    required this.id,
    required this.title,
    this.description = '',
    this.categoryId,
    this.color,
    this.location,
    this.videoLink,
    this.busy = true,
    this.allDay = false,
    required this.start,
    required this.end,
    required this.timeZone,
    this.rrule,
    this.holidayRule = HolidayRule.none,
    this.seriesId,
    this.originalStart,
    this.cancelled = false,
    this.kind = EventKind.event,
    required this.createdAt,
    required this.updatedAt,
  });

  final String id;
  final String title;
  final String description;
  final String? categoryId;

  /// ARGB color overriding the category's one.
  final int? color;
  final String? location;
  final String? videoLink;

  /// Free/busy status: `true` means busy.
  final bool busy;
  final bool allDay;
  final DateTime start;
  final DateTime end;
  final String timeZone;

  /// Recurrence rule (RFC 5545 RRULE subset) of a series master.
  final String? rrule;
  final HolidayRule holidayRule;

  /// For an occurrence (expanded or overridden): id of the series master.
  final String? seriesId;

  /// For an occurrence: its start as generated by the rule, which identifies
  /// it within the series even when it was moved.
  final DateTime? originalStart;

  /// An overridden occurrence that was removed from its series.
  final bool cancelled;
  final EventKind kind;
  final DateTime createdAt;
  final DateTime updatedAt;

  Duration get duration => end.difference(start);

  /// Part of a recurring series (master, expanded or overridden occurrence).
  bool get isRecurring => rrule != null || seriesId != null;

  /// An occurrence generated from its master, not stored in the database.
  bool get isOccurrence => id.contains('@');

  CalendarEvent copyWith({
    String? title,
    String? description,
    String? Function()? categoryId,
    int? Function()? color,
    String? Function()? location,
    String? Function()? videoLink,
    bool? busy,
    bool? allDay,
    DateTime? start,
    DateTime? end,
    String? timeZone,
    String? Function()? rrule,
    HolidayRule? holidayRule,
    String? Function()? seriesId,
    DateTime? Function()? originalStart,
    bool? cancelled,
    String? id,
    DateTime? updatedAt,
  }) {
    return CalendarEvent(
      id: id ?? this.id,
      title: title ?? this.title,
      description: description ?? this.description,
      categoryId: categoryId != null ? categoryId() : this.categoryId,
      color: color != null ? color() : this.color,
      location: location != null ? location() : this.location,
      videoLink: videoLink != null ? videoLink() : this.videoLink,
      busy: busy ?? this.busy,
      allDay: allDay ?? this.allDay,
      start: start ?? this.start,
      end: end ?? this.end,
      timeZone: timeZone ?? this.timeZone,
      rrule: rrule != null ? rrule() : this.rrule,
      holidayRule: holidayRule ?? this.holidayRule,
      seriesId: seriesId != null ? seriesId() : this.seriesId,
      originalStart: originalStart != null
          ? originalStart()
          : this.originalStart,
      cancelled: cancelled ?? this.cancelled,
      kind: kind,
      createdAt: createdAt,
      updatedAt: updatedAt ?? this.updatedAt,
    );
  }

  @override
  bool operator ==(Object other) =>
      other is CalendarEvent &&
      other.id == id &&
      other.title == title &&
      other.description == description &&
      other.categoryId == categoryId &&
      other.color == color &&
      other.location == location &&
      other.videoLink == videoLink &&
      other.busy == busy &&
      other.allDay == allDay &&
      other.start == start &&
      other.end == end &&
      other.timeZone == timeZone &&
      other.rrule == rrule &&
      other.holidayRule == holidayRule &&
      other.seriesId == seriesId &&
      other.originalStart == originalStart &&
      other.cancelled == cancelled &&
      other.kind == kind &&
      other.createdAt == createdAt &&
      other.updatedAt == updatedAt;

  @override
  int get hashCode => Object.hash(
    id,
    title,
    description,
    categoryId,
    color,
    location,
    videoLink,
    busy,
    allDay,
    start,
    end,
    timeZone,
    rrule,
    seriesId,
    originalStart,
    cancelled,
    kind,
    updatedAt,
  );

  @override
  String toString() =>
      'CalendarEvent($id, $title, $start → $end'
      '${allDay ? ', all day' : ''})';
}
